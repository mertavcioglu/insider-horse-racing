test('animates both accordion panels and settles after a rapid reversal', async ({ page, openRace }) => {
  await openRace()
  await page.getByRole('button', { name: 'Generate Program' }).press('Enter')
  const program = page.locator('#program-round-1')
  const trigger = page.locator('#program-round-1-heading')
  const height = () => program.evaluate(node => node.getBoundingClientRect().height)
  const intrinsicHeight = () => program.locator('table').evaluate(node => node.getBoundingClientRect().height)
  const fullHeight = await intrinsicHeight()
  await expect.poll(height).toBe(fullHeight)
  await expect(program.locator('.round-content-inner')).toHaveCSS('overflow', 'hidden')
  const cardBottom = () => page.locator('#program-title').evaluate(node => node.parentElement!.getBoundingClientRect().bottom)
  const fullBottom = await cardBottom()
  await trigger.press('Enter')
  await expect(trigger).toHaveAttribute('aria-expanded', 'false')
  const halfwayHeight = await program.evaluate(node => {
    const motion = node.getAnimations().find(animation => (animation as CSSTransition).transitionProperty === 'grid-template-rows')
    if (!motion) throw new Error('Expected grid collapse transition')
    motion.pause()
    motion.currentTime = 110
    return node.getBoundingClientRect().height
  })
  expect(halfwayHeight).toBeGreaterThan(0)
  expect(halfwayHeight).toBeLessThan(fullHeight)
  expect(await cardBottom()).toBe(fullBottom)
  await trigger.press('Enter')
  await trigger.press('Enter')
  await trigger.press('Enter')
  await expect(trigger).toHaveAttribute('aria-expanded', 'true')
  await expect.poll(height).toBe(fullHeight)
  expect(await cardBottom()).toBe(fullBottom)

  await page.getByRole('button', { name: 'Start', exact: true }).press('Enter')
  await page.clock.fastForward(25_000)
  const result = page.locator('#result-round-1')
  const resultTrigger = page.locator('#result-round-1-heading')
  await expect.poll(() => result.evaluate(node => node.getBoundingClientRect().height)).toBeGreaterThan(300)
  await resultTrigger.press('Space')
  await expect(result).toHaveCSS('transition-duration', '0.22s, 0.22s')
  await expect(result).toBeHidden()
  await resultTrigger.press('Enter')
  await expect.poll(() => result.evaluate(node => node.getBoundingClientRect().height)).toBeGreaterThan(300)
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await resultTrigger.press('Space')
  await expect(result).toHaveCSS('transition-duration', '0s')
  await expect(resultTrigger.locator('.chevron')).toHaveCSS('transition-duration', '0s')
  await expect(result).toBeHidden()
})

test('keeps track, start and finish labels, first lane, and leaderboard at the same height through winner states', async ({ page, openRace }) => {
  await openRace()
  const generate = page.getByRole('button', { name: 'Generate Program' })
  const track = page.getByRole('region', { name: 'Race Track', exact: true })
  const winner = track.locator('.winner-announcement')
  const coordinates = () => track.evaluate(node => {
    window.scrollTo(0, 0)
    return ['.track', '.track-labels span:first-child', '.track-labels span:last-child', '.lanes li', '.leaderboard']
      .map(selector => node.querySelector(selector)?.getBoundingClientRect().top ?? null)
  })
  for (const width of [375, 768, 1024, 1440]) {
    await page.setViewportSize({ width, height: 900 })
    await generate.press('Enter')
    const ready = await coordinates()
    await page.getByRole('button', { name: 'Start', exact: true }).press('Enter')
    await expect(track.locator('h2 > [aria-hidden="true"]')).toHaveText('Race Track')
    const running = await coordinates()
    expect(running.slice(0, 4)).toEqual(ready.slice(0, 4))
    await page.getByRole('button', { name: 'Pause', exact: true }).press('Enter')
    expect(await coordinates()).toEqual(running)
    await page.getByRole('button', { name: 'Resume', exact: true }).press('Enter')
    await page.clock.fastForward(25_000)
    await expect(winner).toBeVisible()
    await expect(track.getByRole('heading', { name: 'Race Track', exact: true })).toBeVisible()
    await expect(track.getByRole('status')).toContainText('Winner:')
    expect(await coordinates()).toEqual(running)
    await page.clock.runFor(1499)
    await expect(winner).toBeVisible()
    await page.clock.runFor(1)
    await expect(winner).toHaveCount(0)
    expect(await coordinates()).toEqual(running)
    await page.getByRole('button', { name: 'Stop', exact: true }).press('Enter')
    await page.getByRole('button', { name: 'End Race' }).press('Enter')
    expect((await coordinates()).slice(0, 4)).toEqual(ready.slice(0, 4))
    expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBe(width)
  }
})
